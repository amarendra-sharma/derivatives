function buildCases() {
  var B = mkBook(), c = [];
  c.push(caseGreeks(B)); c.push(caseLimits(B));
  c.push(caseHedge(B));
  c.push(caseScenario(B)); c.push(caseStress(B));
  c.push(caseExotic(B)); c.push(caseNote(B));
  return c;
}

