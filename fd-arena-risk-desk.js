function rdDI(S, K, H, r, sig, T) {
  var st = sig * Math.sqrt(T), lam = (r + sig * sig / 2) / (sig * sig), y = Math.log(H * H / (S * K)) / st + lam * st;
  return S * Math.pow(H / S, 2 * lam) * ncdf(y) - K * Math.exp(-r * T) * Math.pow(H / S, 2 * lam - 2) * ncdf(y - st);
}
