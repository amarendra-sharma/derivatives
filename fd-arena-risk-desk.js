function caseHedge(B) {
  return {
    stage: 2, pts: 16, title: "Make the book neutral",
    html: function () { return bookTable(B) + "<p>A traded three-month call with a strike of $" + B.h.K + " has a delta of " + num(B.h.d, 4) + ", a gamma of " + num(B.h.g, 4) + ", and a vega of " + num(B.h.v, 4) + " per point.</p>" + numRow("hg-n", "(a) Number of traded calls to buy to make the book gamma-neutral (negative to sell; nearest whole option)") + numRow("hg-s", "(b) Then the number of shares to buy to make it delta-neutral (negative to sell; nearest whole share)") + numRow("hg-v", "(c) Vega of the hedged book, per percentage point"); },
    grade: function () {
      var a = readNum("hg-n"), b = readNum("hg-s"), c = readNum("hg-v"); if (!need(a, b, c)) { return null; }
      var e = (close(a, B.nh, 1.01) ? 6 : 0) + (close(b, B.sh, 1.6 + Math.abs(B.h.d)) ? 6 : 0) + (close(c, B.V2, 0.06 + 1.01 * Math.abs(B.h.v), 0.002) ? 4 : 0);
      return { earned: e, your: num(a, 0) + "; " + num(b, 0) + "; " + fmtQ(c), correct: num(B.nh, 0) + "; " + num(B.sh, 0) + "; " + fmtQ(B.V2),
        explain: "(a) n = −Γ/Γ_option = −(" + fmtQ(B.G) + ")/" + num(B.h.g, 4) + " ≈ " + num(B.nh, 0) + ". (b) Delta after the options: " + fmtQ(B.D) + " + " + num(B.nh, 0) + " × " + num(B.h.d, 4) + " = " + fmtQ(B.D + B.nh * B.h.d) + "; trade " + num(B.sh, 0) + " shares. (c) Shares carry no vega: " + fmtQ(B.V) + " + " + num(B.nh, 0) + " × " + num(B.h.v, 4) + " = " + fmtQ(B.V2) + ". The hedge that removes gamma also removes much of the vega, because both come from options." };
    },
    
  };
}

/* ---------- stage 3 ---------- */
function pnl(D, G, V, dS, dv) { return D * dS + 0.5 * G * dS * dS + V * dv; }
function caseScenario(B) {
  var dS = rf(-0.08, 0.08, 0.01) * B.S; if (Math.abs(dS) < 0.02 * B.S) { dS = 0.05 * B.S; } dS = rnd2(dS);
  var dv = pick([-4, -3, -2, 2, 3, 4, 5]);
  var u = pnl(B.D, B.G, B.V, dS, dv), h = pnl(B.D2, B.G2, B.V2, dS, dv);
  return {
    stage: 3, pts: 16, title: "A day on the desk",
    html: function () { return bookTable(B) + "<p>Overnight the share price moves by " + (dS < 0 ? "−" : "+") + money(Math.abs(dS), 2) + " and volatility by " + (dv > 0 ? "+" : "−") + Math.abs(dv) + " percentage points. Use the approximation Δ·δS + ½Γ·δS² + V·δσ.</p>" + numRow("sc-u", "(a) Change in value of the unhedged book (dollars)") + numRow("sc-h", "(b) Change in value of the book hedged as in the previous case (dollars), using its delta " + fmtQ(B.D2) + ", gamma " + num(B.G2, 4) + ", and vega " + fmtQ(B.V2)); },
    grade: function () {
      var a = readNum("sc-u"), b = readNum("sc-h"); if (!need(a, b)) { return null; }
      var e = (close(a, u, 2, 0.004) ? 9 : 0) + (close(b, h, 2, 0.004) ? 7 : 0);
      return { earned: e, your: money(a, 0) + "; " + money(b, 0), correct: money(u, 0) + "; " + money(h, 0),
        explain: "(a) (" + fmtQ(B.D) + ")(" + num(dS, 2) + ") + ½(" + fmtQ(B.G) + ")(" + num(dS, 2) + ")² + (" + fmtQ(B.V) + ")(" + num(dv, 0) + ") = " + money(u, 0) + ". (b) The hedged book has almost no delta or gamma, so its result comes from vega: " + money(h, 0) + ". Delta–gamma hedging protects against the price; it leaves exposure to volatility." };
    },
    
  };
}
function caseStress(B) {
  var sc = [ { s: -0.1, v: 8 }, { s: 0.1, v: -4 }, { s: -0.2, v: 15 }, { s: 0.2, v: 5 } ], vals = [], i, worst = Infinity, wi = 0, rows = [];
  for (i = 0; i < sc.length; i++) { var dS = rnd2(sc[i].s * B.S), x = pnl(B.D, B.G, B.V, dS, sc[i].v); vals.push(x); if (x < worst) { worst = x; wi = i; } rows.push(["Scenario " + (i + 1), (dS < 0 ? "−" : "+") + money(Math.abs(dS), 2) + " (" + (sc[i].s > 0 ? "+" : "−") + Math.abs(sc[i].s * 100) + "%)", (sc[i].v > 0 ? "+" : "−") + Math.abs(sc[i].v) + " points"]); }
  var breach = rnd() < 0.5, lim = worst < 0 ? Math.round(-worst * (breach ? rf(0.6, 0.85, 0.05) : rf(1.15, 1.5, 0.05)) / 1000) * 1000 : 1000;
  if (lim <= 0) { lim = 1000; }
  var isB = worst < -lim, labels = ["The book breaches the stress-loss limit", "The book is within the stress-loss limit"];
  return {
    stage: 3, pts: 14, title: "Stress test",
    html: function () { return bookTable(B) + "<p>Risk management stresses the <em>unhedged</em> book under four scenarios, using the delta–gamma–vega approximation. The desk's stress-loss limit is " + money(lim) + ".</p>" + table(["Scenario", "Share price", "Volatility"], rows, "Stress scenarios") + numRow("ss-w", "(a) Change in value in the worst scenario (dollars; negative for a loss)") + lab("(b) Compared with the limit") + mcHtml("ss-m", labels); },
    grade: function () {
      var a = readNum("ss-w"), m = MC["ss-m"]; if (!need(a, m)) { return null; }
      var e = (close(a, worst, 2, 0.004) ? 9 : 0) + (m === (isB ? 0 : 1) ? 5 : 0);
      return { earned: e, your: money(a, 0) + "; " + labels[m], correct: money(worst, 0) + "; " + labels[isB ? 0 : 1],
        explain: "Values by scenario: " + vals.map(function (v, k) { return (k + 1) + ": " + money(v, 0); }).join("; ") + ". The worst is scenario " + (wi + 1) + ", " + money(worst, 0) + ", " + (isB ? "beyond" : "within") + " the limit of " + money(lim) + ". For moves of 20 percent the approximation is rough; a full revaluation of each option is the better test. Value at risk computed from normal markets would not reveal this loss." };
    },
    
  };
}

