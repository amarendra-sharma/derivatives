function caseBuild(v) {
  var tLegs = strat(v.id).legs(v.a, v.b), names = ["Bull call spread", "Bear put spread", "Long straddle", "Long strangle", "Butterfly spread", "Bull put spread"], ids = ["bullCall", "bearPut", "straddle", "strangle", "butterfly", "bullPut"];
  var kl = ["$40", "$45", "$50", "$55", "$60"];
  function userLegs() { var s = MC["u-s"], a = MC["u-a"], b = MC["u-b"]; if (typeof s !== "number" || typeof a !== "number" || typeof b !== "number") { return null; } var k1 = KS[Math.min(a, b)], k2 = KS[Math.max(a, b)]; return strat(ids[s]).legs(k1, k2); }
  function draw() { var u = userLegs(), ser = [{ legs: tLegs, label: "Target", dash: "7 5", color: "#b87408" }]; if (u) { ser.push({ legs: u, label: "Your position", color: "#0f3d9e" }); } var box = $("u-svg"); if (box) { box.innerHTML = profitChart(ser, "Target profit diagram (dashed) with your position overlaid"); } }
  return {
    stage: 3, pts: 14, title: "Build the position",
    onChange: draw, after: draw,
    html: function () { return "<p><b>View.</b> " + v.t + "</p>" + premTable() + "<p class=\"note\">Choose the strategy and its strikes. For a straddle choose the same strike twice; for a butterfly choose the two outer strikes (the middle strike is halfway between).</p>" + lab("Strategy") + mcHtml("u-s", names) + lab("Lower strike") + mcHtml("u-a", kl) + lab("Upper strike") + mcHtml("u-b", kl) + '<div class="svgbox" id="u-svg"></div>'; },
    grade: function () {
      var s = MC["u-s"], a = MC["u-a"], b = MC["u-b"]; if (!need(s, a, b)) { return null; }
      var k1 = KS[Math.min(a, b)], k2 = KS[Math.max(a, b)], okS = ids[s] === v.id, okK = k1 === v.a && k2 === v.b;
      return { earned: (okS ? 8 : 0) + (okS && okK ? 6 : 0), your: names[s] + ", $" + k1 + "/$" + k2, correct: strat(v.id).name + ", $" + v.a + "/$" + v.b,
        explain: "The view calls for a " + strat(v.id).name.toLowerCase() + ": " + legsText(tLegs) + "." + (okS && !okK ? " The strategy is right; the strikes do not place the kinks where the view requires." : "") };
    },
    
  };
}

