function caseProfit() {
  var id = pick(["bullCall", "bearPut", "butterfly", "bearCall", "bullPut"]), s = strat(id), k = id === "butterfly" ? pick([[40, 60], [45, 55]]) : pick([[45, 55], [40, 50], [50, 60]]);
  var legs = s.legs(k[0], k[1]), sT = pick([38, 42, 47, 49, 52, 53, 58, 63]), per = legsProfit(legs, sT), n = pick([1, 2, 5, 10]), tot = rnd2(per * 100 * n);
  return {
    stage: 2, pts: 12, title: "Profit at expiration",
    html: function () { return "<p>A trader builds a " + s.name.toLowerCase() + " with " + n + " contract" + (n > 1 ? "s" : "") + " per leg (100 shares each): " + legsText(legs) + ", at the premiums below. At expiration the share price is $" + sT + ".</p>" + premTable() + numRow("p-p", "Total profit (negative for a loss)"); },
    grade: function () {
      var v = readNum("p-p"); if (!need(v)) { return null; }
      var parts = legs.map(function (L) { return (L.d > 0 ? "+" : "−") + (L.q > 1 ? L.q + "×" : "") + "(" + (L.t === "c" ? "max(" + sT + "−" + L.k + ",0)" : "max(" + L.k + "−" + sT + ",0)") + " − " + num(L.t === "c" ? PREM.c[L.k] : PREM.p[L.k], 2) + ")"; });
      return { earned: close(v, tot, 0.6) ? 12 : 0, your: money(v, 2), correct: money(tot, 2), explain: "Per share: " + parts.join(" ") + " = " + num(per, 2) + ". Total = " + num(per, 2) + " × 100 × " + n + " = " + money(tot, 2) + "." };
    },
    
  };
}
function caseBreakeven() {
  var strg = rnd() < 0.5, k1 = strg ? pick([45, 40]) : 50, k2 = strg ? (k1 === 45 ? 55 : 60) : 50;
  var cost = strg ? PREM.p[k1] + PREM.c[k2] : PREM.c[50] + PREM.p[50], lo = k1 - cost, hi = k2 + cost;
  return {
    stage: 2, pts: 12, title: "Breakeven points",
    html: function () { return "<p>An investor buys a " + (strg ? "strangle: a put at $" + k1 + " and a call at $" + k2 : "straddle at $50: a call and a put") + ", with six months to expiration, at the premiums below.</p>" + premTable() + numRow("b-l", "(a) Lower breakeven share price") + numRow("b-h", "(b) Upper breakeven share price"); },
    grade: function () {
      var a = readNum("b-l"), b = readNum("b-h"); if (!need(a, b)) { return null; }
      var e = (close(a, lo, 0.011) ? 6 : 0) + (close(b, hi, 0.011) ? 6 : 0);
      return { earned: e, your: money(a, 2) + "; " + money(b, 2), correct: money(lo, 2) + "; " + money(hi, 2),
        explain: "Total premium " + num(cost, 2) + ". The position breaks even when the option in the money pays the premium back: " + k1 + " − " + num(cost, 2) + " = " + money(lo, 2) + " and " + k2 + " + " + num(cost, 2) + " = " + money(hi, 2) + "." };
    },
    
  };
}

