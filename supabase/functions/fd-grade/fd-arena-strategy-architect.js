function caseLimits() {
  var id = pick(["bullCall", "bearPut", "butterfly"]), k = id === "butterfly" ? pick([[40, 60], [45, 55]]) : pick([[45, 55], [40, 50], [50, 60], [45, 50]]);
  var legs = strat(id).legs(k[0], k[1]), debit = -legsProfit(legs, id === "bearPut" ? 70 : 0.0001);
  if (id === "butterfly") { debit = -legsProfit(legs, 30); }
  var width = id === "butterfly" ? (k[1] - k[0]) / 2 : k[1] - k[0], maxP = width - debit, maxL = -debit;
  return {
    stage: 4, pts: 14, title: "Maximum profit and loss",
    html: function () { return "<p>A trader buys a " + strat(id).name.toLowerCase() + ": " + legsText(legs) + ", at the premiums below.</p>" + premTable() + numRow("l-p", "(a) Maximum profit per share") + numRow("l-l", "(b) Maximum loss per share (as a negative number)"); },
    grade: function () {
      var a = readNum("l-p"), b = readNum("l-l"); if (!need(a, b)) { return null; }
      var e = (close(a, maxP, 0.011) ? 7 : 0) + (close(b, maxL, 0.011) || close(b, -maxL, 0.011) ? 7 : 0);
      return { earned: e, your: money(a, 2) + "; " + money(b, 2), correct: money(maxP, 2) + "; " + money(maxL, 2),
        explain: "Net premium paid = " + num(debit, 2) + ", the most that can be lost. The most the payoff can reach is " + num(width, 0) + " (" + (id === "butterfly" ? "at the middle strike" : "the distance between the strikes") + "), so the maximum profit is " + num(width, 0) + " − " + num(debit, 2) + " = " + money(maxP, 2) + "." };
    },
    
  };
}
function caseBox() {
  var k = pick([[40, 50], [45, 55], [50, 60], [40, 60]]), fair = (k[1] - k[0]) * Math.exp(-RF * TT), q = rnd2(fair + rf(0.15, 0.6, 0.05) * (rnd() < 0.5 ? 1 : -1)), cheap = q < fair, n = pick([5, 10, 20]);
  var prof = Math.abs(fair - q) * 100 * n;
  var labels = ["Buy the box (bull call spread + bear put spread)", "Sell the box (the opposite of each leg)", "No arbitrage"];
  return {
    stage: 4, pts: 14, title: "The box spread",
    html: function () { return "<p>European options on the share have six months to expiry and the risk-free rate is " + pc(RF, 1) + " (continuous compounding). A dealer will trade a box spread with strikes $" + k[0] + " and $" + k[1] + " at a net price of " + money(q, 2) + " per share.</p>" + lab("(a) The arbitrage") + mcHtml("x-mc", labels) + numRow("x-p", "(b) Present value of the riskless profit on " + n + " boxes (100 shares each)"); },
    grade: function () {
      var m = MC["x-mc"], v = readNum("x-p"); if (!need(m, v)) { return null; }
      var e = (m === (cheap ? 0 : 1) ? 6 : 0) + (close(v, prof, 0.6, 0.002) ? 8 : 0);
      return { earned: e, your: labels[m] + "; " + money(v, 2), correct: labels[cheap ? 0 : 1] + "; " + money(prof, 2),
        explain: "The box pays $" + (k[1] - k[0]) + " for certain, so it is worth " + (k[1] - k[0]) + "e^(−" + RF + "×" + TT + ") = " + money(fair, 4) + ". The quote is " + (cheap ? "below" : "above") + " that: " + (cheap ? "buy" : "sell") + " it. Profit = " + num(Math.abs(fair - q), 4) + " × 100 × " + n + " = " + money(prof, 2) + "." };
    },
    
  };
}

function buildCases() {
  PREM = premiums();
  var c = [], two = shuffle(["bullCall", "bearPut", "butterfly", "straddle", "strangle", "bearCall", "bullPut", "shortStraddle"]);
  c.push(caseName(two[0])); c.push(caseName(two[1]));
  var s2 = shuffle([caseProfit, caseBreakeven]); c.push(s2[0]()); c.push(s2[1]());
  var v = shuffle(VIEWS); c.push(caseBuild(v[0])); c.push(caseBuild(v[1]));
  var s4 = shuffle([caseLimits, caseBox]); c.push(s4[0]()); c.push(s4[1]());
  return c;
}

