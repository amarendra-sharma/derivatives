function caseCva() {
  var f = rf(1, 9, 0.25) * 1e6, lam = rf(0.005, 0.04, 0.005), R = pick([0.3, 0.35, 0.4, 0.45, 0.5]), T = ri(1, 5);
  var pd = 1 - Math.exp(-lam * T), cva = (1 - R) * f * pd;
  var labels = ["Zero: a written option is never an asset to the dealer", "The same as the company's CVA", "(1 − R) times the premium the dealer received", "The company's CVA multiplied by the dealer's hazard rate"];
  return {
    stage: 4, pts: 14, title: "The CVA of an option",
    html: function () { return "<p>A company buys from a dealer a " + T + "-year European option, settled at expiration and not collateralized, whose value ignoring default is " + money(f) + ". The dealer's risk-neutral hazard rate is " + pc(lam, 1) + " and its recovery rate " + Math.round(R * 100) + " percent.</p>" + numRow("cv-p", "(a) Probability that the dealer defaults during the life of the option") + numRow("cv-v", "(b) Credit value adjustment to the company (dollars)") + lab("(c) The dealer's own CVA on this option, with respect to the company, is") + mcHtml("cv-m", labels); },
    grade: function () {
      var a = readNum("cv-p"), b = readNum("cv-v"), m = MC["cv-m"]; if (!need(a, b, m)) { return null; }
      var e = (close(prIn(a), pd, 0.0006) ? 4 : 0) + (close(b, cva, 10, 0.003) ? 7 : 0) + (m === 0 ? 3 : 0);
      return { earned: e, your: num(prIn(a), 4) + "; " + money(b) + "; " + labels[m], correct: num(pd, 4) + "; " + money(Math.round(cva)) + "; " + labels[0],
        explain: "(a) 1 − e^(−" + num(lam, 3) + "×" + T + ") = " + num(pd, 4) + ". (b) The expected exposure of a purchased option is its value, so CVA = (1 − R) × f₀ × PD = " + num(1 - R, 2) + " × " + money(f) + " × " + num(pd, 4) + " = " + money(Math.round(cva)) + "; the option is worth " + money(Math.round(f - cva)) + " from this dealer. (c) The dealer's position is a liability throughout, so its exposure, and CVA, are zero." };
    },
    
  };
}
function caseNetting() {
  var vals = [ri(4, 15), -ri(2, 12), ri(1, 8), -ri(1, 10), ri(1, 6)], i, gross = 0, tot = 0, rows = [];
  for (i = 0; i < vals.length; i++) { if (vals[i] > 0) { gross += vals[i]; } tot += vals[i]; rows.push(["Trade " + (i + 1), (vals[i] < 0 ? "−" : "+") + "$" + Math.abs(vals[i]) + " million"]); }
  var net = Math.max(tot, 0), coll = rf(0, Math.max(net, 1), 0.5), after = Math.max(net - coll, 0);
  if (coll > net) { coll = net; after = 0; }
  return {
    stage: 4, pts: 16, title: "Netting and collateral",
    html: function () { return "<p>A dealer has five uncollateralized derivatives with one counterparty. Their values to the dealer are:</p>" + table(["Trade", "Value to the dealer"], rows) + numRow("nt-g", "(a) Exposure without a netting agreement ($ million)") + numRow("nt-n", "(b) Exposure with a netting agreement ($ million)") + numRow("nt-c", "(c) Exposure with netting if the counterparty has posted collateral of $" + num(coll, 1) + " million ($ million)"); },
    grade: function () {
      var a = readNum("nt-g"), b = readNum("nt-n"), c = readNum("nt-c"); if (!need(a, b, c)) { return null; }
      var sc = function (x) { return Math.abs(x) >= 1000 ? x / 1e6 : x; };
      var e = (close(sc(a), gross, 0.01) ? 5 : 0) + (close(sc(b), net, 0.01) ? 6 : 0) + (close(sc(c), after, 0.01) ? 5 : 0);
      return { earned: e, your: num(sc(a), 1) + "; " + num(sc(b), 1) + "; " + num(sc(c), 1), correct: num(gross, 1) + "; " + num(net, 1) + "; " + num(after, 1),
        explain: "(a) Without netting, contracts with a negative value must still be paid in full, so the exposure is the sum of the positive values: $" + gross + " million. (b) With netting the contracts are one: max(" + tot + ", 0) = $" + net + " million. (c) Collateral held reduces the netted exposure: max(" + net + " − " + num(coll, 1) + ", 0) = $" + num(after, 1) + " million." };
    },
    
  };
}

function buildCases() {
  var c = [];
  c.push(caseSurvival()); c.push(caseSpread());
  var s2 = shuffle([caseCds, caseMtm]); c.push(s2[0]()); c.push(s2[1]());
  c.push(caseSettle());
  var s4 = shuffle([caseCva, caseNetting]); c.push(s4[0]()); c.push(s4[1]());
  return c;
}

