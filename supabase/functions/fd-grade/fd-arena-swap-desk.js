function caseValue() {
  var L = pick([50, 100, 200]) * 1e6, k = rf(0.03, 0.06, 0.0025), t1 = pick([0.25, 0.3333333333, 0.4166666667]), n = 3, ts = [], z = [], i, rows = [];
  for (i = 0; i < n; i++) { ts.push(t1 + 0.5 * i); z.push(rndN(rf(0.030, 0.050, 0.0005) + 0.001 * i, 4)); rows.push([Math.round(ts[i] * 12) + " months", num(z[i] * 100, 2) + "%"]); }
  var lastFl = rf(0.03, 0.06, 0.0005), kstar = L * lastFl * 0.5, recFixed = rnd() < 0.5;
  var Bfix = 0; for (i = 0; i < n; i++) { Bfix += L * k * 0.5 * Math.exp(-z[i] * ts[i]); } Bfix += L * Math.exp(-z[n - 1] * ts[n - 1]);
  var Bfl = (L + kstar) * Math.exp(-z[0] * ts[0]), V = (recFixed ? 1 : -1) * (Bfix - Bfl);
  return {
    stage: 3, pts: 16, title: "Value an existing swap",
    html: function () {
      return "<p>A financial institution <b>" + (recFixed ? "receives" : "pays") + "</b> " + pc(k, 2) + " per annum fixed and " + (recFixed ? "pays" : "receives") + " six-month floating on a notional of " + money(L) + ", with semiannual payments. The swap has " + n + " payments left, the next in " + Math.round(t1 * 12) + " months. The floating rate set at the last reset was " + pc(lastFl, 2) + " (semiannual compounding). Zero rates are:</p>" + table(["Payment date", "Zero rate"], rows) +
        numRow("v-x", "(a) B_fix, the value of the fixed-rate bond") + numRow("v-l", "(b) B_fl, the value of the floating-rate bond") + numRow("v-v", "(c) Value of the swap to the institution");
    },
    grade: function () {
      var a = readNum("v-x"), b = readNum("v-l"), c = readNum("v-v"); if (!need(a, b, c)) { return null; }
      var tol = Math.max(50, L * 0.000005);
      var e = (close(a, Bfix, tol) ? 5 : 0) + (close(b, Bfl, tol) ? 5 : 0) + (close(c, V, tol * 1.5) ? 6 : 0);
      return { earned: e, your: money(a) + "; " + money(b) + "; " + money(c), correct: money(Bfix) + "; " + money(Bfl) + "; " + money(V),
        explain: "(a) Fixed coupons " + money(L * k * 0.5) + " at each date plus the principal at the last: B_fix = " + money(Bfix) + ". (b) The next floating payment is k* = " + money(L) + " × " + num(lastFl, 4) + " × 0.5 = " + money(kstar) + "; B_fl = (" + money(L) + " + " + money(kstar) + ")e^(−" + num(z[0], 4) + "×" + num(ts[0], 4) + ") = " + money(Bfl) + ". (c) " + (recFixed ? "Receiving fixed: B_fix − B_fl" : "Paying fixed: B_fl − B_fix") + " = " + money(V) + "." };
    },
    
  };
}
