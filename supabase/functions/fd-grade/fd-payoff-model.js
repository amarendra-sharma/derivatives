function legProfit(leg, s) {
  if (leg.type === "call") { return leg.dir * (Math.max(s - leg.k, 0) - leg.prem); }
  if (leg.type === "put") { return leg.dir * (Math.max(leg.k - s, 0) - leg.prem); }
  if (leg.type === "fwd") { return leg.dir * (s - leg.k); }
  return leg.dir * (s - leg.k);   /* stock bought at k */
}
function legsProfit(legs, s) { var t = 0, i; for (i = 0; i < legs.length; i++) { t += legProfit(legs[i], s); } return t; }

