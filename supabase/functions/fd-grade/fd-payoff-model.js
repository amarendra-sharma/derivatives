/* A piecewise-linear profit line must be clipped to the frame at the exact
   crossing, otherwise clamping bends it. Add frame crossings as extra kinks. */
function kinksFor(legs, cfg) {
  var ks = [], i, x;
  for (i = 0; i < legs.length; i++) { if (legs[i].type === "call" || legs[i].type === "put") { ks.push(legs[i].k); } }
  var pts = [cfg.xmin].concat(ks).concat([cfg.xmax]).sort(function (a, b) { return a - b; });
  var out = ks.slice();
  for (i = 0; i < pts.length - 1; i++) {
    var y1 = legsProfit(legs, pts[i]), y2 = legsProfit(legs, pts[i + 1]);
    var lims = [cfg.ymin, cfg.ymax], j;
    for (j = 0; j < 2; j++) {
      if ((y1 - lims[j]) * (y2 - lims[j]) < 0) { x = pts[i] + (lims[j] - y1) / (y2 - y1) * (pts[i + 1] - pts[i]); out.push(x); }
    }
  }
  return out;
}
function legsDiagram(legs, cfg) { return { fn: function (s) { return legsProfit(legs, s); }, kinks: kinksFor(legs, cfg) }; }

