var seed = 1;
function rnd() { /* mulberry32 */
  seed |= 0; seed = (seed + 0x6D2B79F5) | 0;
  var t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
function ri(a, b) { return Math.floor(rnd() * (b - a + 1)) + a; }
function pick(arr) { return arr[ri(0, arr.length - 1)]; }
function shuffle(arr) { var a = arr.slice(), i, j, t; for (i = a.length - 1; i > 0; i--) { j = ri(0, i); t = a[i]; a[i] = a[j]; a[j] = t; } return a; }
/* Tolerant numeric parser: accepts $, commas, %, spaces, a unicode minus,
   accounting parentheses for negatives, and simple fractions (5/8). */
function parseNum(raw) {
  if (raw === null || raw === undefined) { return NaN; }
  var s = String(raw).replace(/[\s,$%]/g, "").replace(/−/g, "-");
  if (s === "") { return NaN; }
  var neg = false;
  if (/^\(.*\)$/.test(s)) { neg = true; s = s.substring(1, s.length - 1); }
  var v;
  if (/^-?\d+(\.\d+)?\/\d+(\.\d+)?$/.test(s)) { var p = s.split("/"); v = parseFloat(p[0]) / parseFloat(p[1]); }
  else if (/^-?(\d+\.?\d*|\.\d+)$/.test(s)) { v = parseFloat(s); }
  else { return NaN; }
  return neg ? -v : v;
}
