function caseAntithetic() {
  var S = rf(40, 100, 1), K = rnd2(S * rf(0.95, 1.05, 0.01)), r = rf(0.02, 0.06, 0.0025), sig = rf(0.18, 0.40, 0.01), T = 1, eps = [], i, rows = [], vals = [];
  for (i = 0; i < 3; i++) {
    eps.push(rndN(gauss(), 4));
    var up = S * Math.exp((r - sig * sig / 2) * T + sig * eps[i]), dn = S * Math.exp((r - sig * sig / 2) * T - sig * eps[i]);
    vals.push((Math.max(up - K, 0) + Math.max(dn - K, 0)) / 2);
    rows.push(["Pair " + (i + 1), num(eps[i], 4)]);
  }
  var est = Math.exp(-r * T) * (vals[0] + vals[1] + vals[2]) / 3;
  return {
    stage: 2, pts: 12, title: "Antithetic variates",
    html: function () { return "<p>A one-year European call (S0 = " + money(S, 2) + ", K = " + money(K, 2) + ", σ = " + pc(sig, 0) + ", r = " + pc(r, 2) + ") is valued with antithetic variates. Each draw ε below is paired with −ε.</p>" + table(["Pair", "ε"], rows) + numRow("a-1", "(a) Average payoff of pair 1 (the two payoffs averaged)") + numRow("a-e", "(b) Estimate of the call value from the three pairs"); },
    grade: function () {
      var a = readNum("a-1"), b = readNum("a-e"); if (!need(a, b)) { return null; }
      var e = (close(a, vals[0], 0.011) ? 5 : 0) + (close(b, est, 0.011) ? 7 : 0);
      return { earned: e, your: num(a, 4) + "; " + num(b, 4), correct: num(vals[0], 4) + "; " + num(est, 4),
        explain: "For each pair the prices are S0 exp((r − σ²/2) ± σε); pair averages " + vals.map(function (x) { return num(x, 4); }).join(", ") + ". Estimate e^(−" + num(r, 4) + ") × mean = " + num(est, 4) + "." };
    },
    
  };
}

