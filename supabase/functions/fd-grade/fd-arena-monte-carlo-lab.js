      var e = (close(x, limit, 0.000002, 0.035) ? 5 : 0) + (m === (stable ? 0 : 1) ? 5 : 0);
      return { earned: e, your: num(x, 6) + "; " + (m === 0 ? "stable" : "unstable"), correct: num(limit, 6) + "; " + (stable ? "stable" : "unstable"),
        explain: "b_j ∝ 1 − σ²j²Δt is smallest at the top node, so the condition is Δt ≤ 1/(σ²j_max²) = 1/(" + num(sig * sig, 4) + " × " + (jmax * jmax) + ") = " + num(limit, 6) + ". Δt = " + num(dt, 4) + " is " + (stable ? "within" : "above") + " it." + (stable ? "" : " Errors then grow at each step and the values oscillate; the implicit method, or a smaller Δt, is needed.") };
