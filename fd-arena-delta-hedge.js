function caseVega() {
  var D = pick([-1, 1]) * rf(0, 1500, 50), G = -rf(2000, 6000, 100), V = -rf(4000, 9000, 100);
  var o1 = { d: rf(0.5, 0.7, 0.01), g: rf(1.0, 2.0, 0.1), v: rf(0.8, 1.6, 0.1) }, o2 = { d: rf(0.3, 0.6, 0.01), g: rf(0.3, 0.9, 0.1), v: rf(1.8, 3.0, 0.1) };
  var det = o1.g * o2.v - o2.g * o1.v, w1 = (-G * o2.v + V * o2.g) / det, w2 = (-V * o1.g + G * o1.v) / det;
  var newD = D + w1 * o1.d + w2 * o2.d;
  return {
    stage: 3, pts: 18, title: "Gamma and vega neutral together",
    html: function () { return "<p>A portfolio has delta " + num(D, 0) + ", gamma " + num(G, 0) + " and vega " + num(V, 0) + ". Two traded options are available:</p>" + table(["Option", "Delta", "Gamma", "Vega"], [["Option 1", num(o1.d, 2), num(o1.g, 1), num(o1.v, 1)], ["Option 2", num(o2.d, 2), num(o2.g, 1), num(o2.v, 1)]]) + numRow("v-1", "(a) Quantity of option 1 (negative to sell)") + numRow("v-2", "(b) Quantity of option 2 (negative to sell)") + numRow("v-s", "(c) Shares to trade afterwards for delta neutrality"); },
    grade: function () {
      var a = readNum("v-1"), b = readNum("v-2"), c = readNum("v-s"); if (!need(a, b, c)) { return null; }
      var t1 = Math.max(2, Math.abs(w1) * 0.005), t2 = Math.max(2, Math.abs(w2) * 0.005);
      var e = (close(a, w1, t1) ? 6 : 0) + (close(b, w2, t2) ? 6 : 0) + (close(c, -newD, Math.max(3, Math.abs(newD) * 0.006)) ? 6 : 0);
      return { earned: e, your: num(a, 0) + "; " + num(b, 0) + "; " + num(c, 0), correct: num(w1, 0) + "; " + num(w2, 0) + "; " + num(-newD, 0),
        explain: "Solve " + num(G, 0) + " + " + num(o1.g, 1) + "w1 + " + num(o2.g, 1) + "w2 = 0 and " + num(V, 0) + " + " + num(o1.v, 1) + "w1 + " + num(o2.v, 1) + "w2 = 0: w1 = " + num(w1, 1) + ", w2 = " + num(w2, 1) + ". Delta becomes " + num(D, 0) + " + " + num(w1 * o1.d, 1) + " + " + num(w2 * o2.d, 1) + " = " + num(newD, 1) + "; trade " + num(-newD, 0) + " shares." };
    },
    
  };
}

