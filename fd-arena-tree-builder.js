/* ---------- stage 3 ---------- */
function caseAmerican() {
  var S, u, d, r, dt, K, p, ex, f, fB, fC, euro, tries = 0;
  do {
    S = rf(40, 60, 1); u = rf(1.10, 1.25, 0.01); d = rnd2(1 / u); r = rf(0.04, 0.09, 0.0025); dt = pick([0.5, 1]); K = rnd2(S * rf(1.00, 1.12, 0.01));
    p = (Math.exp(r * dt) - d) / (u - d);
    var N = nodesOf(S, u, d), D_ = Math.max(K - N.D, 0), E_ = Math.max(K - N.E, 0), F_ = Math.max(K - N.F, 0), disc = Math.exp(-r * dt);
    var contB = disc * (p * D_ + (1 - p) * E_), contC = disc * (p * E_ + (1 - p) * F_);
    fB = Math.max(contB, K - N.B); fC = Math.max(contC, K - N.C);
    ex = []; if (K - N.B > contB + 1e-9) { ex.push("B"); } if (K - N.C > contC + 1e-9) { ex.push("C"); }
    var contA = disc * (p * fB + (1 - p) * fC); f = Math.max(contA, K - S); if (K - S > contA + 1e-9) { ex = ["A"]; }
    euro = disc * disc * (p * p * D_ + 2 * p * (1 - p) * E_ + (1 - p) * (1 - p) * F_);
    tries++;
  } while ((ex.length === 0 ? rnd() < 0.7 : false) && tries < 60);
  var exI = ex.length === 0 ? 3 : (ex[0] === "A" ? 0 : (ex[0] === "B" ? 1 : 2));
  var NN = nodesOf(S, u, d), nB = NN.B, nC = NN.C, cB = Math.exp(-r * dt) * (p * Math.max(K - NN.D, 0) + (1 - p) * Math.max(K - NN.E, 0)), cC = Math.exp(-r * dt) * (p * Math.max(K - NN.E, 0) + (1 - p) * Math.max(K - NN.F, 0));
  var labels = ["At node A (immediately)", "At node B", "At node C", "At no node"];
  return {
    stage: 3, pts: 16, title: "An American put",
    html: function () { return "<p>An American put with strike " + money(K, 2) + " expires after two steps of " + (dt === 1 ? "one year" : "six months") + " each. The share price tree has u = " + num(u, 2) + " and d = " + num(d, 2) + ", and the risk-free rate is " + pc(r, 2) + ".</p>" + treeSvg(S, u, d, "Two-step share price tree with nodes A to F") + lab("(a) At which node, if any, is early exercise optimal?") + mcHtml("a-mc", labels) + numRow("a-f", "(b) Value of the American put at node A"); },
    grade: function () {
      var m = MC["a-mc"], v = readNum("a-f"); if (!need(m, v)) { return null; }
      var e = (m === exI ? 6 : 0) + (close(v, f, 0.0011, 0.0003) ? 10 : 0);
      return { earned: e, your: labels[m] + "; " + num(v, 4), correct: labels[exI] + "; " + num(f, 4),
        explain: "p = " + num(p, 4) + ". At B: continuing is worth " + num(cB, 4) + ", exercising " + num(Math.max(K - nB, 0), 4) + ". At C: continuing " + num(cC, 4) + ", exercising " + num(Math.max(K - nC, 0), 4) + ". Taking the larger at each node and discounting back gives " + num(f, 4) + " at A (the European put would be worth " + num(euro, 4) + ")." };
    },
    
  };
}

