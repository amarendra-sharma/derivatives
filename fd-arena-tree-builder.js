function caseOther() {
  var kind = pick(["index", "currency", "futures"]), sig = rf(0.15, 0.35, 0.01), dt = pick([0.25, 0.5]), r = rf(0.03, 0.06, 0.0025), q = rf(0.01, 0.03, 0.0025), rfo = rf(0.01, 0.05, 0.0025);
  var u = Math.exp(sig * Math.sqrt(dt)), d = 1 / u, a = kind === "index" ? Math.exp((r - q) * dt) : (kind === "currency" ? Math.exp((r - rfo) * dt) : 1), p = (a - d) / (u - d);
  var S = kind === "index" ? rf(3800, 5200, 50) : (kind === "currency" ? rf(1.05, 1.30, 0.01) : rf(60, 90, 1));
  var K = kind === "index" ? S : (kind === "currency" ? S : S), f = Math.exp(-r * dt) * (p * Math.max(S * u - K, 0) + (1 - p) * Math.max(S * d - K, 0));
  var txt = kind === "index" ? "a stock index at " + num(S, 0) + " with a dividend yield of " + pc(q, 2) : (kind === "currency" ? "a foreign currency at $" + num(S, 2) + " with a foreign risk-free rate of " + pc(rfo, 2) : "a futures price of " + money(S, 2));
  return {
    stage: 4, pts: 16, title: "A tree for " + (kind === "index" ? "an index" : (kind === "currency" ? "a currency" : "a futures contract")),
    html: function () { return "<p>A one-step tree with a step of " + Math.round(dt * 12) + " months is built for " + txt + " and a volatility of " + pc(sig, 0) + ". The dollar risk-free rate is " + pc(r, 2) + ". u = e^(σ√Δt) and d = 1/u.</p>" + numRow("o-p", "(a) Risk-neutral probability p") + numRow("o-f", "(b) Value of an at-the-money European call over that step"); },
    grade: function () {
      var x = readNum("o-p"), y = readNum("o-f"); if (!need(x, y)) { return null; }
      var e = (close(x, p, 0.0006) ? 8 : 0) + (close(y, f, Math.max(0.0011, f * 0.0005)) ? 8 : 0);
      return { earned: e, your: num(x, 4) + "; " + num(y, 4), correct: num(p, 4) + "; " + num(f, 4),
        explain: "u = " + num(u, 4) + ", d = " + num(d, 4) + ". The growth factor is a = " + (kind === "index" ? "e^((r − q)Δt) = " : (kind === "currency" ? "e^((r − r_f)Δt) = " : "1 (a futures contract costs nothing to enter) = ")) + num(a, 6) + "; p = (a − d)/(u − d) = " + num(p, 4) + ". The call pays " + num(S * u - K, 4) + " after an up move and 0 after a down move; f = e^(−rΔt) p (" + num(S * u - K, 4) + ") = " + num(f, 4) + "." };
    },
    
  };
}
function caseNodeDelta() {
  var S = rf(40, 80, 1), u = rf(1.08, 1.18, 0.01), d = rnd2(1 / u), r = rf(0.02, 0.06, 0.0025), dt = 0.25, K = rnd2(S * rf(0.97, 1.03, 0.01));
  var p = (Math.exp(r * dt) - d) / (u - d), disc = Math.exp(-r * dt);
  var N = nodesOf(S, u, d), D_ = Math.max(N.D - K, 0), E_ = Math.max(N.E - K, 0), F_ = Math.max(N.F - K, 0);
  var fB = disc * (p * D_ + (1 - p) * E_), fC = disc * (p * E_ + (1 - p) * F_), dA = (fB - fC) / (N.B - N.C), dB = (D_ - E_) / (N.D - N.E);
  return {
    stage: 4, pts: 14, title: "Delta at a node",
    html: function () { return "<p>A European call with strike " + money(K, 2) + " expires after two three-month steps on the tree below (u = " + num(u, 2) + ", d = " + num(d, 2) + "; risk-free rate " + pc(r, 2) + ").</p>" + treeSvg(S, u, d, "Two-step share price tree with nodes A to F") + numRow("x-a", "(a) Delta at node A") + numRow("x-b", "(b) Delta at node B"); },
    grade: function () {
      var a = readNum("x-a"), b = readNum("x-b"); if (!need(a, b)) { return null; }
      var e = (close(a, dA, 0.0011) ? 8 : 0) + (close(b, dB, 0.0011) ? 6 : 0);
      return { earned: e, your: num(a, 4) + "; " + num(b, 4), correct: num(dA, 4) + "; " + num(dB, 4),
        explain: "Values at B and C: " + num(fB, 4) + " and " + num(fC, 4) + ". Δ_A = (" + num(fB, 4) + " − " + num(fC, 4) + ")/(" + num(N.B, 2) + " − " + num(N.C, 2) + ") = " + num(dA, 4) + ". Δ_B = (" + num(D_, 4) + " − " + num(E_, 4) + ")/(" + num(N.D, 2) + " − " + num(N.E, 2) + ") = " + num(dB, 4) + ". Delta changes as the tree is traversed, which is why a hedge must be rebalanced." };
    },
    
  };
}

function buildCases() {
  var c = [];
  var s1 = shuffle([caseDelta, caseRN]); c.push(s1[0]()); c.push(s1[1]());
  var s2 = shuffle([caseTwoStep, caseCRR]); c.push(s2[0]()); c.push(s2[1]());
  c.push(caseAmerican());
  var s4 = shuffle([caseOther, caseNodeDelta]); c.push(s4[0]()); c.push(s4[1]());
  return c;
}

