var FDA = {
  SLUG: SLUG, TITLE: ARENA.title, MAX_ATTEMPTS: MAX_ATTEMPTS, PASS: PASS, STAGES: STAGES,
  build: function (s) { seed = s | 0; MC = {}; return buildCases(); },
  /* Re-grade a whole submitted run. answers[i] = { mc: {...}, inp: {id: value} }. */
  gradeRun: function (s, answers) {
    var cases = FDA.build(s), out = [], total = 0, i, g, a;
    answers = answers || [];
    for (i = 0; i < cases.length; i++) {
      a = answers[i] || {};
      MC = (a.mc && typeof a.mc === "object") ? a.mc : {};
      FD_INPUTS = (a.inp && typeof a.inp === "object") ? a.inp : {};
      try { g = cases[i].grade(); } catch (e) { g = null; }
      FD_INPUTS = null; MC = {};
      if (!g) { g = { earned: 0, your: "(no answer)", correct: "", explain: "" }; }
      if (typeof g.earned !== "number" || !(g.earned >= 0)) { g.earned = 0; }
      if (g.earned > cases[i].pts) { g.earned = cases[i].pts; }
      g.earned = Math.round(g.earned * 100) / 100;
      total += g.earned;
      out.push({ stage: cases[i].stage, title: cases[i].title, pts: cases[i].pts, earned: g.earned,
                 your: String(g.your), correct: String(g.correct), explain: String(g.explain) });
    }
    return { cases: out, earned: Math.round(total * 100) / 100, max: FDA.MAX_POINTS };
  }
};
