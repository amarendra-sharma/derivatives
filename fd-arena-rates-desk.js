function caseSOFR() {
  var L = pick([5, 10, 15, 20, 30]) * 1e6, borrow = rnd() < 0.6, Q = rndN(100 - rf(3.6, 5.2, 0.005), 3), Rimp = 100 - Q;
  var Rend = rndN(Rimp + rf(-0.7, 0.7, 0.01), 3), n = L / 1e6, gain = rnd2((borrow ? 1 : -1) * (Rend - Rimp) * 100 * 25 * n);
  return {
    stage: 4, pts: 12, title: "Fix a rate with SOFR futures",
    html: function () {
      return "<p>A company will " + (borrow ? "borrow" : "deposit") + " " + money(L) + " for three months, starting at the expiry of a three-month SOFR futures contract quoted today at " + num(Q, 3) + ".</p>" +
        lab("(a) Position") + mcHtml("q-side", ["Buy contracts", "Sell contracts"]) + numRow("q-n", "(b) Number of contracts") +
        numRow("q-g", "(c) At expiry the three-month rate is " + num(Rend, 3) + "%. Gain on the futures position (negative for a loss)");
    },
    grade: function () {
      var sd = MC["q-side"], k = readNum("q-n"), g = readNum("q-g"); if (!need(sd, k, g)) { return null; }
      var e = (sd === (borrow ? 1 : 0) ? 4 : 0) + (close(k, n, 0.01) ? 4 : 0) + (close(g, gain, 1) ? 4 : 0);
      return { earned: e, your: ["Buy", "Sell"][sd] + "; " + num(k, 0) + "; " + money(g), correct: (borrow ? "Sell" : "Buy") + "; " + n + "; " + money(gain),
        explain: "The quote implies a rate of 100 − " + num(Q, 3) + " = " + num(Rimp, 3) + "%. A " + (borrow ? "borrower loses when rates rise, and a short futures position gains when rates rise (the quote falls)" : "depositor loses when rates fall, and a long futures position gains when rates fall (the quote rises)") + ". One contract per $1,000,000: " + n + " contracts. Gain = (" + (borrow ? num(Rend, 3) + " − " + num(Rimp, 3) : num(Rimp, 3) + " − " + num(Rend, 3)) + ") × 100 basis points × $25 × " + n + " = " + money(gain) + ", which offsets the change in interest and fixes the rate near " + num(Rimp, 3) + "%." };
    },
    
  };
}
function caseCTD() {
  var Fq = rf(108, 116, 0.25), bonds = [], i, best = 0;
  for (i = 0; i < 3; i++) {
    var cf = rf(0.80, 1.45, 0.0001), cost = rf(0.05, 2.4, 0.01);
    bonds.push({ cf: cf, q: rnd2(Fq * cf + cost), cost: cost });
  }
  for (i = 0; i < 3; i++) { bonds[i].cost = rnd2(bonds[i].q - Fq * bonds[i].cf); }
  for (i = 1; i < 3; i++) { if (bonds[i].cost < bonds[best].cost - 1e-9) { best = i; } }
  /* ensure a clear winner */
  if (Math.abs(bonds[(best + 1) % 3].cost - bonds[best].cost) < 0.05 || Math.abs(bonds[(best + 2) % 3].cost - bonds[best].cost) < 0.05) { bonds[best].q = rnd2(bonds[best].q - 0.15); bonds[best].cost = rnd2(bonds[best].q - Fq * bonds[best].cf); }
  var ai = rf(0.4, 2.6, 0.01), inv = (Fq * bonds[best].cf + ai) * 1000;
  var rows = []; for (i = 0; i < 3; i++) { rows.push(["Bond " + "ABC".charAt(i), num(bonds[i].q, 2), num(bonds[i].cf, 4)]); }
  return {
    stage: 4, pts: 14, title: "The cheapest-to-deliver bond",
    html: function () {
      return "<p>The settlement price of a Treasury bond futures contract is " + num(Fq, 2) + ". The party with the short position may deliver any of three bonds (prices per $100 of principal):</p>" + table(["Bond", "Quoted price", "Conversion factor"], rows) +
        lab("(a) Which bond is cheapest to deliver?") + mcHtml("t-b", ["Bond A", "Bond B", "Bond C"]) +
        numRow("t-i", "(b) Accrued interest on that bond is " + num(ai, 2) + " per $100. Cash received for delivering $100,000 of principal");
    },
    grade: function () {
      var b = MC["t-b"], v = readNum("t-i"); if (!need(b, v)) { return null; }
      var e = (b === best ? 8 : 0) + (close(v, inv, 1) ? 6 : 0);
      var costs = []; for (i = 0; i < 3; i++) { costs.push("ABC".charAt(i) + ": " + num(bonds[i].q, 2) + " − " + num(Fq, 2) + "×" + num(bonds[i].cf, 4) + " = " + num(bonds[i].cost, 3)); }
      return { earned: e, your: "Bond " + "ABC".charAt(b) + "; " + money(v), correct: "Bond " + "ABC".charAt(best) + "; " + money(inv),
        explain: "(a) The cost of delivering each bond is its quoted price less what the short receives for it, settlement price × conversion factor: " + costs.join("; ") + ". The smallest is bond " + "ABC".charAt(best) + ". (b) (" + num(Fq, 2) + " × " + num(bonds[best].cf, 4) + " + " + num(ai, 2) + ") × 1,000 = " + money(inv) + "." };
    },
    
  };
}
function caseDuration() {
  var VP = pick([5, 8, 10, 12, 20, 25]) * 1e6, DP = rf(3.5, 9.5, 0.1), Fq = rf(105, 118, 0.25), DF = rf(7, 11, 0.1), VF = Fq * 1000;
  var acquire = rnd() < 0.3, N = VP * DP / (VF * DF), dy = pick([0.25, 0.5, 0.75, 1.0]) / 100;
  var dPort = -VP * DP * dy;
  return {
    stage: 4, pts: 12, title: "A duration-based hedge",
    html: function () {
      return "<p>A fund " + (acquire ? "will buy in three months" : "holds") + " a bond portfolio worth " + money(VP) + " with a duration of " + num(DP, 1) + " years and hedges it with Treasury bond futures quoted at " + num(Fq, 2) + " (contract size $100,000 of principal). The cheapest-to-deliver bond will have a duration of " + num(DF, 1) + " years at the contract's maturity.</p>" +
        lab("(a) Position") + mcHtml("u-s", ["Long futures", "Short futures"]) + numRow("u-n", "(b) Number of contracts (to one decimal)") +
        numRow("u-d", "(c) Approximate change in the value of the portfolio if all yields rise by " + num(dy * 100, 2) + " percentage points");
    },
    grade: function () {
      var s = MC["u-s"], n = readNum("u-n"), d = readNum("u-d"); if (!need(s, n, d)) { return null; }
      var e = (s === (acquire ? 0 : 1) ? 3 : 0) + (close(n, N, 0.06) ? 6 : 0) + (close(d, dPort, Math.abs(dPort) * 0.002 + 1) ? 3 : 0);
      return { earned: e, your: ["Long", "Short"][s] + "; " + num(n, 1) + "; " + money(d), correct: (acquire ? "Long" : "Short") + "; " + num(N, 1) + "; " + money(dPort),
        explain: "(a) " + (acquire ? "A future buyer of the portfolio is harmed by a fall in yields (a rise in price) and hedges long." : "A holder loses when yields rise and hedges short.") + " (b) V_F = " + num(Fq, 2) + " × 1,000 = " + money(VF) + "; N* = " + money(VP) + " × " + num(DP, 1) + " / (" + money(VF) + " × " + num(DF, 1) + ") = " + num(N, 2) + ". (c) ΔV ≈ −V_P D_P Δy = −" + money(VP) + " × " + num(DP, 1) + " × " + num(dy, 4) + " = " + money(dPort) + "." };
    },
    
  };
}

