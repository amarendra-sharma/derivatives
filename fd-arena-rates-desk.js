function caseForward() {
  var T1 = pick([1, 2, 3]), T2 = T1 + pick([1, 2]), R1 = rf(0.03, 0.05, 0.0005), R2 = rndN(R1 + rf(-0.004, 0.010, 0.0005), 4);
  var F = (R2 * T2 - R1 * T1) / (T2 - T1);
  var shape = R2 > R1 ? 0 : (R2 < R1 ? 1 : 2);
  return {
    stage: 3, pts: 10, title: "A forward rate",
    html: function () {
      return "<p>The " + T1 + "-year zero rate is " + num(R1 * 100, 2) + "% and the " + T2 + "-year zero rate is " + num(R2 * 100, 2) + "%, both with continuous compounding.</p>" + numRow("f-r", "(a) Forward rate for the period from year " + T1 + " to year " + T2 + " (percent, continuous compounding)") +
        lab("(b) The forward rate lies") + mcHtml("f-s", ["Above both zero rates", "Below both zero rates", "Between the two zero rates"]);
    },
    grade: function () {
      var x = readNum("f-r"), s = MC["f-s"]; if (!need(x, s)) { return null; }
      var ans = Math.abs(R2 - R1) < 1e-9 ? 2 : (R2 > R1 ? 0 : 1);
      var e = (closePct(x, F, 0.002) ? 7 : 0) + (s === ans ? 3 : 0);
      return { earned: e, your: num(x, 3) + "%; " + ["above", "below", "between"][s], correct: num(F * 100, 3) + "%; " + ["above", "below", "between (all equal)"][ans],
        explain: "(a) R_F = (" + num(R2 * 100, 2) + " × " + T2 + " − " + num(R1 * 100, 2) + " × " + T1 + ")/(" + T2 + " − " + T1 + ") = " + num(F * 100, 3) + "%. (b) R_F = R2 + (R2 − R1)T1/(T2 − T1): when zero rates " + (R2 > R1 ? "rise with maturity the forward rate exceeds both." : (R2 < R1 ? "fall with maturity the forward rate is below both." : "are flat, all three coincide.")) };
    },
    
  };
}
function caseFRA() {
  var L = pick([10, 15, 20, 25, 40]) * 1e6, T1 = pick([0.25, 0.5, 0.75]), tau = 0.25, T2 = T1 + tau;
  var R1 = rf(0.035, 0.05, 0.0005), R2 = rndN(R1 + rf(-0.001, 0.004, 0.0005), 4);
  var Fc = (R2 * T2 - R1 * T1) / tau, Fq = fromC(Fc, 4), RK = rndN(Fq + rf(-0.004, 0.004, 0.0005), 4);
  var V = L * (Fq - RK) * tau * Math.exp(-R2 * T2);       /* value to the payer of fixed */
  var RM = rndN(RK + rf(-0.009, 0.012, 0.0005), 4), pay = L * (RM - RK) * tau, settle = pay / (1 + RM * tau);
  var mo = function (t) { return Math.round(t * 12) + " months"; };
  return {
    stage: 3, pts: 12, title: "Value and settle an FRA",
    html: function () {
      return "<p>A company will borrow " + money(L) + " in " + mo(T1) + " for three months and has entered an FRA to <b>pay</b> a fixed rate of " + num(RK * 100, 2) + "% (quarterly compounding) on that principal for that period. Zero rates with continuous compounding are " + num(R1 * 100, 2) + "% for " + mo(T1) + " and " + num(R2 * 100, 2) + "% for " + mo(T2) + ".</p>" +
        numRow("a-f", "(a) Forward rate for the period, with quarterly compounding (percent, three decimals)") + numRow("a-v", "(b) Value of the FRA to the company today") +
        numRow("a-s", "(c) The reference rate for the period proves to be " + num(RM * 100, 2) + "%. Amount the company receives at the start of the period (negative if it pays)");
    },
    grade: function () {
      var f = readNum("a-f"), v = readNum("a-v"), s = readNum("a-s"); if (!need(f, v, s)) { return null; }
      var e = (closePct(f, Fq, 0.002) ? 3 : 0) + (close(v, V, Math.max(2, Math.abs(V) * 0.002, L * 0.25 * 0.00001)) ? 5 : 0) + (close(s, settle, 2, 0.0005) ? 4 : 0);
      return { earned: e, your: num(f, 3) + "%; " + money(v) + "; " + money(s), correct: num(Fq * 100, 3) + "%; " + money(V) + "; " + money(settle),
        explain: "(a) Continuous forward rate (" + num(R2 * 100, 2) + " × " + num(T2, 2) + " − " + num(R1 * 100, 2) + " × " + num(T1, 2) + ")/0.25 = " + num(Fc * 100, 3) + "%, quarterly 4(e^(" + num(Fc, 5) + "/4) − 1) = " + num(Fq * 100, 3) + "%. (b) The payer of fixed is worth L(R_F − R_K)τe^(−R2T2) = " + money(L) + " × (" + num(Fq, 5) + " − " + num(RK, 4) + ") × 0.25 × e^(−" + num(R2, 4) + "×" + num(T2, 2) + ") = " + money(V) + ". (c) Payoff at the end of the period " + money(L) + " × (" + num(RM, 4) + " − " + num(RK, 4) + ") × 0.25 = " + money(pay) + "; settled at the start, discounted at the reference rate: " + money(pay) + "/(1 + " + num(RM, 4) + " × 0.25) = " + money(settle) + "." };
    },
    
  };
}

