  var s = String(raw).replace(/[\s,$%£€]/g, "").replace(/−/g, "-");
  if (s === "") { return NaN; }
  var neg = false;
  if (/^\(.*\)$/.test(s)) { neg = true; s = s.substring(1, s.length - 1); }
  var v;
  if (/^-?\d+(\.\d+)?\/\d+(\.\d+)?$/.test(s)) { var p = s.split("/"); v = parseFloat(p[0]) / parseFloat(p[1]); }
  else if (/^-?(\d+\.?\d*|\.\d+)(e-?\d+)?$/i.test(s)) { v = parseFloat(s); }
