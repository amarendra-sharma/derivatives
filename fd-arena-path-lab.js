function ncdf(x) { /* Hart / West double precision */
  var z = Math.abs(x), c = 0;
  if (z <= 37) {
    var e = Math.exp(-z * z / 2);
    if (z < 7.07106781186547) {
      var n = (((((0.0352624965998911 * z + 0.700383064443688) * z + 6.37396220353165) * z + 33.912866078383) * z + 112.079291497871) * z + 221.213596169931) * z + 220.206867912376;
      var d = ((((((0.0883883476483184 * z + 1.75566716318264) * z + 16.064177579207) * z + 86.7807322029461) * z + 296.564248779674) * z + 637.333633378831) * z + 793.826512519948) * z + 440.413735824752;
      c = e * n / d;
    } else {
      var f = z + 1 / (z + 2 / (z + 3 / (z + 4 / (z + 0.65))));
      c = e / f / 2.506628274631;
    }
  }
  return x <= 0 ? c : 1 - c;
}
function npdf(x) { return Math.exp(-x * x / 2) / 2.5066282746310002; }
/* Black-Scholes-Merton with continuous yield q. type "c" or "p". */
function bsm(type, S, K, r, q, sig, T) {
  if (T <= 0 || sig <= 0) { return type === "c" ? Math.max(S - K, 0) : Math.max(K - S, 0); }
  var sq = sig * Math.sqrt(T), d1 = (Math.log(S / K) + (r - q + sig * sig / 2) * T) / sq, d2 = d1 - sq;
  if (type === "c") { return S * Math.exp(-q * T) * ncdf(d1) - K * Math.exp(-r * T) * ncdf(d2); }
  return K * Math.exp(-r * T) * ncdf(-d2) - S * Math.exp(-q * T) * ncdf(-d1);
}
function bsmD(S, K, r, q, sig, T) { var sq = sig * Math.sqrt(T), d1 = (Math.log(S / K) + (r - q + sig * sig / 2) * T) / sq; return { d1: d1, d2: d1 - sq }; }
function bsmGreeks(type, S, K, r, q, sig, T) {
  var d = bsmD(S, K, r, q, sig, T), eq = Math.exp(-q * T), er = Math.exp(-r * T), sT = Math.sqrt(T);
  var delta = type === "c" ? eq * ncdf(d.d1) : eq * (ncdf(d.d1) - 1);
  var gamma = eq * npdf(d.d1) / (S * sig * sT);
  var vega = S * eq * npdf(d.d1) * sT;
  var theta = type === "c"
    ? -S * eq * npdf(d.d1) * sig / (2 * sT) - r * K * er * ncdf(d.d2) + q * S * eq * ncdf(d.d1)
    : -S * eq * npdf(d.d1) * sig / (2 * sT) + r * K * er * ncdf(-d.d2) - q * S * eq * ncdf(-d.d1);
  return { delta: delta, gamma: gamma, vega: vega, theta: theta, d1: d.d1, d2: d.d2 };
}
function impliedVol(type, price, S, K, r, q, T) {
  var lo = 0.0001, hi = 5, i, mid;
  for (i = 0; i < 200; i++) { mid = (lo + hi) / 2; if (bsm(type, S, K, r, q, mid, T) > price) { hi = mid; } else { lo = mid; } }
  return (lo + hi) / 2;
}

