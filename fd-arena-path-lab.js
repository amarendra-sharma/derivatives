/* ---------- stage 3 ---------- */
function caseVol() {
  var weekly = rnd() < 0.4, n = 10, sig = rf(0.18, 0.45, 0.01), tau = weekly ? 1 / 52 : 1 / 252, P = [rf(30, 90, 0.5)], i, u = [], rows = [];
  for (i = 1; i <= n; i++) { P.push(rnd2(P[i - 1] * Math.exp(sig * Math.sqrt(tau) * gauss()))); }
  for (i = 1; i <= n; i++) { u.push(Math.log(P[i] / P[i - 1])); }
  var mean = 0; for (i = 0; i < n; i++) { mean += u[i]; } mean /= n;
  var ss = 0; for (i = 0; i < n; i++) { ss += (u[i] - mean) * (u[i] - mean); } var s = Math.sqrt(ss / (n - 1)), est = s / Math.sqrt(tau);
  for (i = 0; i <= n; i++) { rows.push([(weekly ? "Week " : "Day ") + i, money(P[i], 2)]); }
  return {
    stage: 3, pts: 18, title: "Estimate the volatility",
    html: function () { return "<p>The table gives " + (n + 1) + " consecutive " + (weekly ? "weekly" : "daily") + " closing prices of a share that pays no dividends." + (weekly ? " Use 52 weeks per year." : " Use 252 trading days per year.") + "</p>" + table([weekly ? "Week" : "Day", "Closing price"], rows) + numRow("v-s", "(a) Standard deviation of the " + n + " returns ln(S_i/S_(i−1)) (at least four decimals)") + numRow("v-v", "(b) Estimated volatility per annum (percent)"); },
    grade: function () {
      var a = readNum("v-s"), b = readNum("v-v"); if (!need(a, b)) { return null; }
      var e = (close(a, s, 0.00006) ? 7 : 0) + (closePct(b, est, 0.1) ? 11 : 0);
      return { earned: e, your: num(a, 6) + "; " + num(b, 2) + "%", correct: num(s, 6) + "; " + num(est * 100, 2) + "%",
        explain: "Returns: " + u.map(function (x) { return num(x, 5); }).join(", ") + ". Mean " + num(mean, 6) + ". s = √(Σ(u_i − ū)²/(n − 1)) = " + num(s, 6) + " (dividing by n − 1 = " + (n - 1) + "). σ̂ = s/√τ = " + num(s, 6) + " × √" + (weekly ? 52 : 252) + " = " + num(est * 100, 2) + "%." };
    },
    
  };
}

/* ---------- stage 4 ---------- */
function caseIto() {
  var kind = pick(["ln", "fwd", "sq"]), mu = rf(0.06, 0.16, 0.01), sig = rf(0.15, 0.40, 0.01), r = rf(0.02, 0.06, 0.005);
  var dr, vol, txt, why;
  if (kind === "ln") { dr = mu - sig * sig / 2; vol = sig; txt = "G = ln S"; why = "∂G/∂S = 1/S, ∂²G/∂S² = −1/S², ∂G/∂t = 0, so dG = (μ − σ²/2) dt + σ dz: drift " + num(mu, 2) + " − " + num(sig * sig / 2, 4) + " = " + num(dr, 4) + " and volatility " + num(sig, 2) + "."; }
  else if (kind === "fwd") { dr = mu - r; vol = sig; txt = "the forward price F = S e^(r(T − t)) for a contract on the share, with r = " + pc(r, 1); why = "∂F/∂S = e^(r(T − t)), ∂²F/∂S² = 0, ∂F/∂t = −rF, so dF = (μ − r)F dt + σF dz: proportional drift " + num(mu, 2) + " − " + num(r, 3) + " = " + num(dr, 4) + " and volatility " + num(sig, 2) + "."; }
  else { dr = 2 * mu + sig * sig; vol = 2 * sig; txt = "G = S²"; why = "∂G/∂S = 2S, ∂²G/∂S² = 2, so dG = (2μS² + σ²S²) dt + 2σS² dz = (2μ + σ²)G dt + 2σG dz: proportional drift " + num(dr, 4) + " and volatility " + num(vol, 2) + "."; }
  var propText = kind === "ln" ? "drift (per year, not proportional)" : "proportional drift (per year)";
  return {
    stage: 4, pts: 18, title: "Apply Itô's lemma",
    html: function () { return "<p>A share price follows dS = μS dt + σS dz with μ = " + num(mu, 2) + " and σ = " + num(sig, 2) + ". Find the process followed by " + txt + ".</p>" + numRow("i-d", "(a) The " + propText + ", as a decimal") + numRow("i-v", "(b) The " + (kind === "ln" ? "volatility (coefficient of dz)" : "proportional volatility") + ", as a decimal"); },
    grade: function () {
      var a = readNum("i-d"), b = readNum("i-v"); if (!need(a, b)) { return null; }
      var ok = function (v, t) { return close(v, t, 0.0006) || close(v / 100, t, 0.0006); };
      var e = (ok(a, dr) ? 10 : 0) + (ok(b, vol) ? 8 : 0);
      return { earned: e, your: num(a, 4) + "; " + num(b, 4), correct: num(dr, 4) + "; " + num(vol, 4), explain: why };
    },
    
  };
}
function caseProb() {
  var S = rf(40, 100, 1), K = rnd2(S * rf(0.85, 1.20, 0.01)), mu = rf(0.06, 0.16, 0.01), sig = rf(0.18, 0.40, 0.01), T = pick([0.5, 1]);
  var d = (Math.log(S / K) + (mu - sig * sig / 2) * T) / (sig * Math.sqrt(T)), pr = ncdf(d);
  return {
    stage: 4, pts: 18, title: "The probability of finishing in the money",
    html: function () { return "<p>A share price follows geometric Brownian motion with μ = " + pc(mu, 0) + " and σ = " + pc(sig, 0) + "; today it is " + money(S, 2) + ".</p>" + numRow("p-p", "Real-world probability that it is above " + money(K, 2) + " in " + (T === 1 ? "one year" : "six months")); },
    grade: function () {
      var p = readNum("p-p"); if (!need(p)) { return null; }
      var pp = p > 1 ? p / 100 : p;
      return { earned: close(pp, pr, 0.0011) ? 18 : 0, your: num(pp, 4), correct: num(pr, 4),
        explain: "P(S_T > K) = N((ln(S0/K) + (μ − σ²/2)T)/(σ√T)) = N(" + num(d, 4) + ") = " + num(pr, 4) + ". With μ replaced by r this is N(d2), the risk-neutral probability." };
    },
    
  };
}

function buildCases() {
  var c = [];
  c.push(caseWiener());
  var s2 = shuffle([caseStep, caseLognormal]); c.push(s2[0]()); c.push(s2[1]());
  c.push(caseVol());
  var s4 = shuffle([caseIto, caseProb]); c.push(s4[0]()); c.push(s4[1]());
  return c;
}

