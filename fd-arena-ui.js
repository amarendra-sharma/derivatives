/* fd-arena-ui.js - the page side of every Financial Derivatives arena after the Payoff Lab:
   attempt control, staged cases, feedback, results and recording. The arena's model file
   (fd-arena-<slug>.js) is loaded first and defines SLUG, ARENA, STAGES, MC, CUR and FDA.
   GENERATED by build/build-arenas.py from src/arenas/_ui.js. Safari-safe ES5. */
"use strict";
var RUN = null;
var LS_KEY = "fd.arena." + SLUG;
function loadStore() { try { var r = localStorage.getItem(LS_KEY); if (r) { var o = JSON.parse(r); if (o && o.attempts) { return o; } } } catch (e) {} return { attempts: [] }; }
function saveStore(o) { try { localStorage.setItem(LS_KEY, JSON.stringify(o)); } catch (e) {} }
function backendLive() { return (typeof FDBackend !== "undefined" && FDBackend.isOnline && FDBackend.isOnline()); }
function progressMod() { if (typeof FDProgress !== "undefined") { return FDProgress; } return null; }
function avg(a) { var t = 0, i; for (i = 0; i < a.length; i++) { t += a[i]; } return a.length ? t / a.length : 0; }
function nStages() { return STAGES.length; }

/* SERVER mode: signed in on this site. Attempts come from, and are recorded to, the course
   gradebook; the server rebuilds each run from its seed and grades it itself.
   LOCAL mode: no session (or no backend). Attempts stay in this browser. */
var MODE = "local", SERVER_ATTEMPTS = [], SERVER_ERR = "";
function renderMode() {
  var m = $("pl-mode");
  if (MODE === "server") { m.className = "pl-mode live"; m.textContent = "Graded mode: completed attempts are recorded to your course gradebook."; }
  else if (backendLive()) { m.className = "pl-mode"; m.innerHTML = 'You are not signed in on this page, so attempts are kept in this browser only. <a href="index.html">Sign in through the course portal</a> and return here to record graded attempts.'; }
  else { m.className = "pl-mode"; m.textContent = "Preview mode: the course backend is not connected on this page, so attempts are kept in this browser only and are not recorded to a gradebook."; }
}
function attemptsList() { return MODE === "server" ? SERVER_ATTEMPTS : loadStore().attempts; }
function loadServerAttempts(cb) {
  var sb = FDBackend._sb && FDBackend._sb();
  if (!sb) { cb(false); return; }
  sb.auth.getSession().then(function (r) {
    var s = r && r.data ? r.data.session : null;
    if (!s) { cb(false); return; }
    sb.from("fd_attempt").select("attempt_no,score_pct").eq("arena_slug", SLUG).eq("user_id", s.user.id).then(function (res) {
      if (res.error) { SERVER_ERR = res.error.message; cb(false); return; }
      var by = {}, k, out = [];
      (res.data || []).forEach(function (row) { var a = row.attempt_no || 1; var v = Number(row.score_pct) || 0; if (!(a in by) || v > by[a]) { by[a] = v; } });
      var keys = Object.keys(by).map(Number).sort(function (x, y) { return x - y; });
      for (k = 0; k < keys.length && k < MAX_ATTEMPTS; k++) { out.push(by[keys[k]]); }
      SERVER_ATTEMPTS = out; cb(true);
    }, function () { cb(false); });
  }, function () { cb(false); });
}

function stagePoints() {
  var cs = FDA.build(1), pts = [], i;
  for (i = 0; i < STAGES.length; i++) { pts.push(0); }
  for (i = 0; i < cs.length; i++) { pts[cs[i].stage - 1] += cs[i].pts; }
  return { pts: pts, cases: cs.length };
}
function listWords(a) { return a.length < 2 ? a.join("") : a.slice(0, -1).join(", ") + ", and " + a[a.length - 1]; }
var WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen", "sixteen"];

function renderIntro() {
  var st = { attempts: attemptsList() }, n = st.attempts.length, locked = n >= MAX_ATTEMPTS, sp = stagePoints();
  var h = '<div class="card"><div class="eyebrow">Companion arena &middot; ' + ARENA.chapter + '</div><h2>' + ARENA.title + '</h2>';
  var cw = WORDS[sp.cases] || String(sp.cases), sw = WORDS[STAGES.length] || String(STAGES.length);
  h += "<p>" + cw.charAt(0).toUpperCase() + cw.slice(1) + " cases in " + sw + " stages. " + ARENA.intro + " Each stage opens with a short statement of the principle and each case is followed by a full explanation.</p>";
  h += '<ul class="rules"><li>The arena is worth ' + FDA.MAX_POINTS + ' points: ' + listWords(sp.pts.map(String)) + ' across the ' + sw + ' stages. Partial credit is awarded where a case has several parts.</li><li>The numbers are drawn afresh for every attempt.</li><li>Two graded attempts are allowed. With one attempt the grade is that score; with two, the grade is the average of the two.</li><li>A score of 70 percent or more completes the arena.</li><li>' + (ARENA.inputNote || "Enter losses and outflows as negative numbers. Dollar signs, commas, and percent signs are accepted; a rate may be entered as a percentage (5.25) or a decimal (0.0525).") + '</li></ul>';
  if (n > 0) {
    h += '<table><thead><tr><th>Attempt</th><th class="num">Score</th></tr></thead><tbody>';
    var i; for (i = 0; i < n; i++) { h += "<tr><td>Attempt " + (i + 1) + '</td><td class="num">' + Math.round(st.attempts[i] * 100) + "%</td></tr>"; }
    h += '<tr><th>Arena grade</th><th class="num">' + Math.round(avg(st.attempts) * 100) + "%</th></tr></tbody></table>";
  }
  if (!locked) { h += '<button class="btn" id="start-btn" onclick="startRun(true)">' + (n === 0 ? "Begin attempt 1" : "Begin attempt 2 (optional)") + "</button>"; }
  else { h += "<p><b>Both graded attempts are complete.</b> Further runs are for practice and do not change the grade.</p>" + '<button class="btn ghost" id="start-btn" onclick="startRun(false)">Start an ungraded practice run</button>'; }
  h += "</div>";
  $("stage").innerHTML = h;
}

function startRun(graded) {
  var n = attemptsList().length;
  var s0 = (Date.now() ^ (n * 7919) ^ Math.floor(Math.random() * 1e9)) | 0;
  if (typeof window.__PL_SEED === "number") { s0 = window.__PL_SEED; }
  RUN = { graded: graded && n < MAX_ATTEMPTS, attemptNo: n + 1, seed: s0, cases: FDA.build(s0), i: 0, earned: 0, log: [], answers: [] };
  renderCase();
}

function renderCase() {
  MC = {};
  var c = RUN.cases[RUN.i]; CUR = c;
  var stg = STAGES[c.stage - 1], total = RUN.cases.length;
  var firstOfStage = RUN.i === 0 || RUN.cases[RUN.i - 1].stage !== c.stage;
  var h = '<div class="bar"><div class="stat"><b>Stage ' + stg.n + " of " + nStages() + "</b><span>" + stg.name + '</span></div><div class="stat"><b>Case ' + (RUN.i + 1) + " of " + total + '</b><span>' + (RUN.graded ? "graded attempt " + RUN.attemptNo : "practice run") + '</span></div><div class="stat"><b>' + num(RUN.earned, 0) + '</b><span>points earned so far</span></div></div>';
  h += '<div class="prog"><div style="width:' + Math.round(RUN.i / total * 100) + '%"></div></div>';
  h += '<div class="card">';
  h += '<div class="teach"><p><b>' + (firstOfStage ? "Principle for this stage. " : "Principle. ") + "</b>" + stg.teach + "</p></div>";
  h += '<div class="eyebrow">' + c.title + " &middot; " + c.pts + " points</div>" + c.html();
  h += '<div class="row" style="margin-top:1rem;"><button class="btn" id="submit-btn" onclick="submitCase()">Submit answer</button><span id="need" style="font-size:0.85rem;color:var(--red);"></span></div><div id="fb"></div></div>';
  $("stage").innerHTML = h;
  if (c.after) { c.after(); }
  if (window.renderMathInElement) { try { window.renderMathInElement($("stage"), { delimiters: [{ left: "\\(", right: "\\)", display: false }] }); } catch (e) {} }
  window.scrollTo(0, 0);
}

function submitCase() {
  var c = RUN.cases[RUN.i], g = c.grade();
  if (!g) { $("need").textContent = "Complete every part of the case before submitting. Numeric answers must be numbers."; return; }
  var inp = {}, els = $("stage").querySelectorAll("input[id], select[id]"), k, mc = {}, key;
  for (k = 0; k < els.length; k++) { inp[els[k].id] = els[k].value; }
  for (key in MC) { if (MC.hasOwnProperty(key)) { mc[key] = MC[key]; } }
  RUN.answers[RUN.i] = { mc: mc, inp: inp };
  $("need").textContent = "";
  g.earned = Math.max(0, Math.min(c.pts, Math.round(g.earned * 100) / 100));
  RUN.earned = Math.round((RUN.earned + g.earned) * 100) / 100;
  RUN.log.push({ stage: c.stage, title: c.title, pts: c.pts, earned: g.earned, your: g.your, correct: g.correct, explain: g.explain });
  var cls = g.earned === c.pts ? "good" : (g.earned > 0 ? "part" : "bad");
  var head = g.earned === c.pts ? "Correct. " + c.pts + " of " + c.pts + " points." : (g.earned > 0 ? "Partly correct. " + num(g.earned, g.earned % 1 ? 1 : 0) + " of " + c.pts + " points." : "Not correct. 0 of " + c.pts + " points.");
  var last = RUN.i === RUN.cases.length - 1;
  $("fb").innerHTML = '<div class="fb ' + cls + '"><b>' + head + "</b>Correct answer: " + esc(g.correct) + ".<br>" + esc(g.explain) + '</div><div class="row"><button class="btn" id="next-btn" onclick="nextCase()">' + (last ? "See results" : "Next case") + "</button></div>";
  $("submit-btn").disabled = true;
  var ins = $("stage").querySelectorAll("input, select, .opts button, .ctl"), i;
  for (i = 0; i < ins.length; i++) { ins[i].disabled = true; }
  var nb = $("next-btn"); if (nb) { nb.focus(); }
}
function nextCase() { RUN.i++; if (RUN.i >= RUN.cases.length) { finishRun(); } else { renderCase(); } }

function finishRun() {
  var MAXP = FDA.MAX_POINTS, frac = RUN.earned / MAXP, st = loadStore(), i, S = nStages();
  var stagePts = [], stageMax = [];
  for (i = 0; i < S; i++) { stagePts.push(0); stageMax.push(0); }
  for (i = 0; i < RUN.log.length; i++) { stagePts[RUN.log[i].stage - 1] += RUN.log[i].earned; stageMax[RUN.log[i].stage - 1] += RUN.log[i].pts; }
  var breakdown = [];
  for (i = 0; i < S; i++) { breakdown.push({ label: "Stage " + (i + 1) + " · " + STAGES[i].name, value: num(stagePts[i], stagePts[i] % 1 ? 1 : 0) + " / " + stageMax[i] }); }
  if (RUN.graded && MODE === "server") { st = { attempts: SERVER_ATTEMPTS.concat([frac]) }; }
  if (RUN.graded) {
    if (MODE !== "server") { st.attempts.push(frac); saveStore(st); }
    var grade = avg(st.attempts);
    window._fdResult = { score: grade, outcome: grade >= PASS ? "win" : "completed",
      detail: { explain: ARENA.title + ": " + num(RUN.earned, RUN.earned % 1 ? 1 : 0) + " of " + MAXP + " points on attempt " + RUN.attemptNo + ". Arena grade = average of graded attempts = " + Math.round(grade * 100) + "%.", breakdown: breakdown } };
    var m = progressMod();
    if (m && m.recordArenaAttempt) { try { m.recordArenaAttempt(SLUG, RUN.attemptNo, frac, grade); } catch (e) {} }
    if (m && m.reportArenaNow) { try { m.reportArenaNow(); } catch (e2) {} }
  }
  var h = '<div class="card"><div class="eyebrow">' + (RUN.graded ? "Attempt " + RUN.attemptNo + " complete" : "Practice run complete (ungraded)") + '</div><div class="big ' + (frac >= PASS ? "pass" : "fail") + '">' + num(RUN.earned, RUN.earned % 1 ? 1 : 0) + " / " + MAXP + "</div>";
  h += "<p>" + (frac >= PASS ? "The score meets the 70 percent standard for this arena." : "The score is below the 70 percent standard. Review the explanations below and the corresponding sections of " + ARENA.chapter + ".") + "</p>";
  if (RUN.graded) { h += "<p><b>Arena grade: " + Math.round(avg(st.attempts) * 100) + "%</b> (" + (st.attempts.length === 1 ? "one attempt; a second, optional attempt would be averaged with this one" : "average of two attempts") + ").</p>"; }
  h += '<h3>Points by stage</h3><table><thead><tr><th>Stage</th><th class="num">Points</th></tr></thead><tbody>';
  for (i = 0; i < S; i++) { h += "<tr><td>" + esc(breakdown[i].label) + '</td><td class="num">' + breakdown[i].value + "</td></tr>"; }
  h += '</tbody></table><h3>Case review</h3><table><thead><tr><th>Case</th><th>Your answer</th><th>Correct answer</th><th class="num">Points</th></tr></thead><tbody>';
  for (i = 0; i < RUN.log.length; i++) {
    var L = RUN.log[i];
    h += "<tr><td>" + (i + 1) + ". " + esc(L.title) + "</td><td>" + esc(L.your) + "</td><td>" + esc(L.correct) + '</td><td class="num">' + num(L.earned, L.earned % 1 ? 1 : 0) + " / " + L.pts + '</td></tr><tr><td colspan="4" style="background:var(--bg);font-size:0.8125rem;color:var(--ink-light);">' + esc(L.explain) + "</td></tr>";
  }
  h += '</tbody></table><div class="row"><button class="btn" onclick="renderIntro()">Return to the arena menu</button><a class="btn ghost" style="text-decoration:none;" href="derivatives-textbook.html#' + ARENA.back + '">Return to the textbook</a></div></div>';
  if (RUN.graded && MODE === "server") { h = '<div id="rec" class="pl-mode" role="status">Recording this attempt to your gradebook&hellip;</div>' + h; }
  $("stage").innerHTML = h; CUR = null; window.scrollTo(0, 0);
  if (RUN.graded && MODE === "server") { recordRun(RUN); }
}

/* Post the whole run: the seed and the raw answers. fd-grade rebuilds the cases from the seed
   with this arena's model file, grades the answers itself and assigns the attempt number. */
function recordRun(run) {
  FDBackend.callFn("fd-grade", { arena_slug: SLUG, mode: "arena", seed: run.seed, answers: run.answers }, function (res) {
    var el = $("rec"); if (!el) { return; }
    if (res && res.ok) {
      SERVER_ATTEMPTS.push(res.score);
      el.className = "pl-mode live";
      el.textContent = "Recorded to your gradebook as graded attempt " + res.attempt_no + ": " + num(res.earned, res.earned % 1 ? 1 : 0) + " of " + FDA.MAX_POINTS + " points." +
        (Math.abs(res.earned - run.earned) > 0.001 ? " (The recorded score is the server's grading of your answers.)" : "");
    } else if (res && res.code === "ATTEMPTS_USED") {
      el.className = "pl-mode"; el.textContent = "Not recorded: both graded attempts are already on file. This run counts as practice.";
    } else if (res && res.offline) {
      el.className = "pl-mode"; el.textContent = "Not recorded: the session has expired or the network is unavailable. Sign in again through the course portal and repeat the attempt.";
    } else {
      el.className = "pl-mode"; el.textContent = "Not recorded: " + String(res && res.error ? res.error : "the gradebook did not respond") + ".";
    }
  });
}

function boot() {
  renderMode(); renderIntro();
  if (backendLive()) { loadServerAttempts(function (ok) { MODE = ok ? "server" : "local"; renderMode(); if (!RUN) { renderIntro(); } }); }
  var m = progressMod();
  if (m && m.initArena) { try { m.initArena({ slug: SLUG, getSession: function () { return window._fdResult; } }); } catch (e) {} }
}
if (document.readyState === "loading") { document.addEventListener("DOMContentLoaded", boot); } else { boot(); }
