    if (kind === "CC" && oi - q < 0) { kind = "OO"; }
    var b = who[i], s = who[(i + 3) % 6];
    var tb = kind[0] === "O" ? "opens a long position" : "closes a short position", ts = kind[1] === "O" ? "opens a short position" : "closes a long position";
