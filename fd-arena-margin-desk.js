function caseOrder() {
  var sp = pick(SPECS), P = pick(sp.F), st = rndN(roundTick(P - rf(sp.step[0], sp.step[1], sp.tick), sp.tick), 6);
  var kind = pick(["stopSell", "limitBuy", "stopBuy", "limitSell"]), lvl, seq, fill, txt, why;
  var d = rf(sp.step[0], sp.step[1], sp.tick);
  var p1 = rndN(roundTick(P - d, sp.tick), 6), p2 = rndN(roundTick(P - 2.2 * d, sp.tick), 6), p3 = rndN(roundTick(P + 0.8 * d, sp.tick), 6);
  if (kind === "stopSell") { lvl = rndN(roundTick(P - 1.6 * d, sp.tick), 6); seq = [p1, p2, p3]; txt = "a <b>stop order to sell</b> at " + price(sp, lvl); fill = 1;
    why = "A stop order to sell becomes a market order once the price reaches the stop price or lower. The first trade at or below " + price(sp, lvl) + " is the second one, " + price(sp, p2) + "; the order then executes at the best available price, about " + price(sp, p2) + "."; }
  else if (kind === "limitBuy") { lvl = rndN(roundTick(P - 1.6 * d, sp.tick), 6); seq = [p1, p2, p3]; txt = "a <b>limit order to buy</b> at " + price(sp, lvl); fill = 1;
    why = "A limit order to buy executes only at the limit price or lower. The first trade at or below " + price(sp, lvl) + " is the second one, " + price(sp, p2) + "; the order may fill there or at the limit, never above " + price(sp, lvl) + "."; }
  else if (kind === "stopBuy") { lvl = rndN(roundTick(P + 0.5 * d, sp.tick), 6); seq = [p1, p2, p3]; txt = "a <b>stop order to buy</b> at " + price(sp, lvl); fill = 2;
    why = "A stop order to buy becomes a market order once the price rises to the stop price or higher. Only the third trade, " + price(sp, p3) + ", reaches " + price(sp, lvl) + "."; }
  else { lvl = rndN(roundTick(P + 1.5 * d, sp.tick), 6); seq = [p1, p2, p3]; txt = "a <b>limit order to sell</b> at " + price(sp, lvl); fill = 3;
    why = "A limit order to sell executes only at the limit price or higher. No trade reaches " + price(sp, lvl) + ", so the order is not filled."; }
  var labels = ["After the first trade", "After the second trade", "After the third trade", "It is not filled"];
  return {
    stage: 4, pts: 10, title: "Stop and limit orders",
    html: function () {
      return "<p>A " + sp.name + " futures contract last traded at " + price(sp, P) + ". A trader places " + txt + ". The next three trades take place at " + price(sp, seq[0]) + ", " + price(sp, seq[1]) + ", and " + price(sp, seq[2]) + ", in that order.</p>" + lab("When is the order triggered or filled?") + mcHtml("r-when", labels);
    },
    grade: function () {
      var v = MC["r-when"]; if (!need(v)) { return null; }
      return { earned: v === fill ? 10 : 0, your: labels[v], correct: labels[fill], explain: why };
    },
    
  };
}
function caseReserve() {
  var sp = pick(SPECS), n = ri(5, 20), F0 = pick(sp.F), worst = rf(sp.step[1] * 2, sp.step[1] * 5, sp.tick * 10);
  var drop = rndN(roundTick(worst, sp.tick), 6), F1 = rndN(F0 - drop, 6);
  var loss = rnd2(drop * sp.size * n), cushion = (sp.im - sp.mm) * n;
  /* reserve = everything above the posted initial margin the account must be topped up by
     if the price falls by the drop in a single day: the call restores the balance to IM */
  var call = loss > cushion ? loss : 0;
  return {
    stage: 4, pts: 10, title: "Cash in reserve for a hedge",
    html: function () {
      return "<p>A manufacturer hedges a purchase with a long position in " + n + " " + sp.name + " futures contracts (" + num(sp.size, 0) + " " + sp.unit + "s each) at " + price(sp, F0) + ". The initial margin is " + money(sp.im) + " and the maintenance margin " + money(sp.mm) + " per contract. The treasurer wants to know the cash needed if the futures price falls to " + price(sp, F1) + " in a single day.</p>" +
        numRow("v-loss", "(a) Loss on the futures position that day") + numRow("v-call", "(b) Variation margin called that evening (0 if none)") +
        lab("(c) Compared with an otherwise identical forward contract, the futures hedge") + mcHtml("v-cmp", ["Has a different total gain at maturity", "Has the same total gain, but requires cash during its life", "Never requires additional cash"]);
    },
    grade: function () {
      var a = readNum("v-loss"), b = readNum("v-call"), c = MC["v-cmp"]; if (!need(a, b, c)) { return null; }
      var e = (close(Math.abs(a), loss, 0.6) ? 3 : 0) + (close(b, call, 0.6) ? 4 : 0) + (c === 1 ? 3 : 0);
      return { earned: e, your: money(a, 2) + "; " + money(b, 2) + "; " + ["different gain", "same gain, cash needed", "no cash"][c], correct: money(-loss, 2) + "; " + money(call, 2) + "; same gain, cash needed",
        explain: "(a) " + num(drop, pDec(sp)) + " × " + num(sp.size, 0) + " × " + n + " = " + money(loss, 2) + " lost. (b) The balance falls from " + money(sp.im * n) + " to " + money(sp.im * n - loss, 2) + (call > 0 ? ", below the maintenance level of " + money(sp.mm * n) + ", so the call restores it to the initial margin: a deposit equal to the whole loss, " + money(call, 2) + "." : ", which is still above the maintenance level of " + money(sp.mm * n) + ", so no call is made.") + " (c) The total gain on futures and forwards is the same; the futures gain or loss is settled every day, so a hedger must hold cash to meet margin calls even when the hedge is working as intended." };
    },
    
  };
}

function buildCases() {
  var c = [];
  var s1 = shuffle([caseSize, caseConverge]); c.push(s1[0]()); c.push(s1[1]());
  var sides = shuffle([1, -1]);
  c.push(caseDaily(sides[0])); c.push(caseCall()); c.push(caseTrigger());
  var s3 = shuffle([caseClose, caseOI]); c.push(s3[0]()); c.push(s3[1]());
  var s4 = shuffle([caseOrder, caseReserve]); c.push(s4[0]()); c.push(s4[1]());
  c.push(caseDaily(sides[1]));
  /* keep stage order: move the second daily-settlement case into stage 2 */
  var last = c.pop(); c.splice(3, 0, last);
  return c;
}

